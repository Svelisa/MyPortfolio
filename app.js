function applyTranslations(lang) {
  currentLang = lang;

  // Set document direction and language attribute
  document.documentElement.dir = lang === 'he' ? 'rtl' : 'ltr';
  document.documentElement.lang = lang;

  // Update all [data-i18n] text elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Update all [data-i18n-placeholder] input placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });

  // Update language switcher button label and title
  const switchBtn = document.getElementById('lang-switch-btn');
  if (switchBtn) {
    const codeSpan = switchBtn.querySelector('.lang-code');
    const textSpan = switchBtn.querySelector('.lang-text');
    const tooltipSpan = switchBtn.querySelector('.tooltip');
    if (codeSpan && translations[lang]['lang-code']) codeSpan.textContent = translations[lang]['lang-code'];
    if (textSpan && translations[lang]['lang-switch']) textSpan.textContent = translations[lang]['lang-switch'];
    if (tooltipSpan && translations[lang]['lang-switch']) tooltipSpan.textContent = translations[lang]['lang-switch'];
    if (translations[lang]['lang-title']) {
      switchBtn.setAttribute('title', translations[lang]['lang-title']);
      switchBtn.setAttribute('aria-label', translations[lang]['lang-title']);
    }
  }

  // Sync 3D Carousel on language toggle
  if (typeof window.update3DCarouselGlobal === 'function') {
    window.update3DCarouselGlobal();
  }
  if (typeof window.updateLighthouseBeamGlobal === 'function') {
    window.updateLighthouseBeamGlobal();
  }
}

